#!/usr/bin/env bash
# Creates a throw-away release keystore for TEST builds and points keystore.properties at it.
#
# The keystore and keystore.properties are git-ignored: this script is the only thing committed, so
# no secret ever reaches the repository. For a real release, use your own key instead (see
# docs/ANDROID_BUILD.md) - an APK signed with the test key cannot be updated by a build signed with
# another one.
#
# Usage: mobile/android/scripts/make_test_keystore.sh [output-dir] [alias] [password]
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out_dir="${1:-$here/keystore}"
alias_name="${2:-ran-mobile-test}"
password="${3:-ranmobiletest}"

mkdir -p "$out_dir"
ks="$out_dir/ran-mobile-test.jks"

if ! command -v keytool >/dev/null 2>&1; then
    echo "keytool not found: install a JDK 17 (it ships with the Android command line tools)" >&2
    exit 1
fi

if [[ -f "$ks" ]]; then
    echo "keystore already exists: $ks (delete it to regenerate)"
else
    keytool -genkeypair -v \
        -keystore "$ks" \
        -alias "$alias_name" \
        -keyalg RSA -keysize 2048 -validity 10000 \
        -storepass "$password" -keypass "$password" \
        -dname "CN=RAN MOBILE Test, OU=CI, O=RAN MOBILE, L=Bangkok, C=TH"
fi

cat > "$here/keystore.properties" <<PROPS
# Generated by scripts/make_test_keystore.sh - TEST KEY ONLY, never commit this file or the keystore.
ranKeystoreFile=$ks
ranKeystorePassword=$password
ranKeyAlias=$alias_name
ranKeyPassword=$password
PROPS

echo "wrote $here/keystore.properties (alias $alias_name)"
echo "build: (cd $here && ./gradlew assembleRelease -PranServerUrl=https://your.server)"
