#!/usr/bin/env python3
"""Writes the RAN MOBILE app icon (clean-room: every shape is drawn by this script).

Outputs, all generated from the geometry below:

  app/src/main/res/drawable/ic_launcher_background.xml   adaptive-icon background (vector)
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive-icon foreground (vector)
  app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml     adaptive icon (API 26+)
  app/src/main/res/mipmap-anydpi-v26/ic_launcher_round.xml
  app/src/main/res/mipmap-*/ic_launcher.png              legacy rasters (48..192 px)
  docs/assets/app_icon_preview.png                       preview for the docs

The emblem is a stylised sword over a shield with a rising sun, drawn on the 108x108 adaptive-icon
canvas. The foreground stays inside the 66x66 safe zone so no launcher mask clips it.

Requires: Pillow (pip install pillow) for the rasters and the preview.
Run: python3 mobile/android/tools/make_icon.py
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.normpath(os.path.join(HERE, "..", "app", "src", "main", "res"))
DOCS_ASSETS = os.path.normpath(os.path.join(HERE, "..", "..", "..", "docs", "assets"))

# Palette (self-chosen; deep teal night, gold blade, warm sun).
BG_TOP = (0x0E, 0x1F, 0x2E)
BG_BOTTOM = (0x12, 0x3A, 0x3F)
GOLD = (0xF2, 0xC1, 0x4E)
GOLD_DARK = (0xB8, 0x8A, 0x2A)
SUN = (0xFF, 0x8A, 0x3D)
STEEL = (0x4A, 0x6B, 0x7C)
STEEL_DARK = (0x6E, 0x8E, 0x9E)

# Adaptive icon canvas and the safe zone the launcher may show unmasked.
SIZE = 108.0
SAFE = 66.0
CENTER = SIZE / 2.0


SHIELD_TOP = CENTER - 24.0
SHIELD_W = 26.0
SHIELD_H = 54.0
NOTCH = 9.0     # how deep the V in the top edge goes (the sun sits in it)


def shield_path():
    """A heater shield with a V notch in the top edge, centred on the canvas."""
    cx, top, w, h = CENTER, SHIELD_TOP, SHIELD_W, SHIELD_H
    return (
        f"M {cx - w:.2f} {top:.2f} "
        f"L {cx - 7:.2f} {top:.2f} "
        f"L {cx:.2f} {top + NOTCH:.2f} "          # the notch
        f"L {cx + 7:.2f} {top:.2f} "
        f"L {cx + w:.2f} {top:.2f} "
        f"L {cx + w:.2f} {top + h * 0.55:.2f} "
        f"Q {cx + w:.2f} {top + h * 0.94:.2f} {cx:.2f} {top + h:.2f} "
        f"Q {cx - w:.2f} {top + h * 0.94:.2f} {cx - w:.2f} {top + h * 0.55:.2f} "
        f"Z"
    )


def sword_path():
    """A blade pointing up with a guard and a grip, centred on the canvas."""
    cx = CENTER
    tip, guard = CENTER - 16.0, CENTER + 14.0
    half = 4.8
    grip_half, grip_len = 3.2, 13.0
    return (
        f"M {cx:.2f} {tip:.2f} "                       # tip
        f"L {cx + half:.2f} {tip + 11:.2f} "
        f"L {cx + half:.2f} {guard:.2f} "
        f"L {cx + 13:.2f} {guard:.2f} "                # guard, right
        f"L {cx + 13:.2f} {guard + 4:.2f} "
        f"L {cx + grip_half:.2f} {guard + 4:.2f} "
        f"L {cx + grip_half:.2f} {guard + grip_len:.2f} "   # grip, right
        f"L {cx - grip_half:.2f} {guard + grip_len:.2f} "
        f"L {cx - grip_half:.2f} {guard + 4:.2f} "
        f"L {cx - 13:.2f} {guard + 4:.2f} "
        f"L {cx - 13:.2f} {guard:.2f} "
        f"L {cx - half:.2f} {guard:.2f} "
        f"L {cx - half:.2f} {tip + 11:.2f} "
        f"Z"
    )


SUN_R = 12.0
SUN_CY = SHIELD_TOP + NOTCH + 2.0


def sun_path():
    """The sun in the shield's notch: a disc with a ring (a fan of points keeps it a plain path)."""
    cx, cy, r = CENTER, SUN_CY, SUN_R
    pts = []
    steps = 24
    for i in range(steps):
        a = 2.0 * math.pi * i / steps
        pts.append(f"{'M' if i == 0 else 'L'} {cx + r * math.cos(a):.2f} {cy + r * math.sin(a):.2f}")
    pts.append("Z")
    return " ".join(pts)


def hex_rgb(c):
    return "#%02X%02X%02X" % c


def vector(width, height, body):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by mobile/android/tools/make_icon.py - do not edit by hand. -->\n'
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{width}dp" android:height="{height}dp"\n'
        f'    android:viewportWidth="{SIZE:.0f}" android:viewportHeight="{SIZE:.0f}">\n'
        f'{body}'
        '</vector>\n'
    )


def path(d, fill, alpha=None):
    a = f'\n        android:fillAlpha="{alpha}"' if alpha is not None else ""
    return (f'    <path android:pathData="{d}"\n'
            f'        android:fillColor="{fill}"{a} />\n')


def write_vectors():
    drawable = os.path.join(RES, "drawable")
    mipmap = os.path.join(RES, "mipmap-anydpi-v26")
    os.makedirs(drawable, exist_ok=True)
    os.makedirs(mipmap, exist_ok=True)

    # Background: the night sky band plus two lighter bands, so the icon reads well under a mask.
    bg_body = (
        path(f"M 0 0 H {SIZE:.0f} V {SIZE:.0f} H 0 Z", hex_rgb(BG_TOP))
        + path(f"M 0 {SIZE * 0.58:.0f} H {SIZE:.0f} V {SIZE:.0f} H 0 Z", hex_rgb(BG_BOTTOM))
        + path(f"M 0 {SIZE * 0.58:.0f} H {SIZE:.0f} V {SIZE * 0.60:.0f} H 0 Z",
               hex_rgb(GOLD_DARK), alpha="0.55")
    )
    with open(os.path.join(drawable, "ic_launcher_background.xml"), "w", encoding="utf-8") as f:
        f.write(vector(SIZE, SIZE, bg_body))

    stars = ""
    for i, (sx, sy, sr) in enumerate(((20.0, 24.0, 1.6), (88.0, 30.0, 1.2), (30.0, 84.0, 1.1),
                                      (80.0, 86.0, 1.5))):
        stars += path(f"M {sx - sr:.1f} {sy:.1f} A {sr:.1f} {sr:.1f} 0 1 0 {sx + sr:.1f} {sy:.1f} "
                      f"A {sr:.1f} {sr:.1f} 0 1 0 {sx - sr:.1f} {sy:.1f} Z",
                      hex_rgb(STEEL), alpha="0.75")
    fg_body = (
        stars
        + path(shield_path(), hex_rgb(STEEL))
        + path(shield_path(), hex_rgb(BG_TOP), alpha="0.28")   # inner shading
        + path(sun_path(), hex_rgb(SUN))
        + path(sword_path(), hex_rgb(GOLD))
        + path(f"M {CENTER:.2f} {CENTER - 12:.2f} h 1.4 v 22 h -1.4 Z", hex_rgb(GOLD_DARK),
               alpha="0.8")
    )
    with open(os.path.join(drawable, "ic_launcher_foreground.xml"), "w", encoding="utf-8") as f:
        f.write(vector(SIZE, SIZE, fg_body))

    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by mobile/android/tools/make_icon.py (adaptive icon, API 26+). -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
        '</adaptive-icon>\n'
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        with open(os.path.join(mipmap, name), "w", encoding="utf-8") as f:
            f.write(adaptive)
    print("wrote vector icons in", RES)


def _quad(p0, p1, p2, steps=16):
    """Points of a quadratic bezier (used for the shield's bottom curves)."""
    pts = []
    for i in range(steps + 1):
        t = i / steps
        x = (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t ** 2 * p2[0]
        y = (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t ** 2 * p2[1]
        pts.append((x, y))
    return pts


def draw_raster(size, mask=None):
    """Draws the icon at `size` x `size` pixels with the same geometry as the vector icons."""
    from PIL import Image, ImageDraw

    scale = size / SIZE
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    # Background: vertical two-band fill with a thin gold horizon line.
    for y in range(size):
        t = y / max(1, size - 1)
        col = tuple(int(BG_TOP[i] + (BG_BOTTOM[i] - BG_TOP[i]) * t) for i in range(3))
        d.line([(0, y), (size, y)], fill=col + (255,))
    d.line([(0, int(SIZE * 0.58 * scale)), (size, int(SIZE * 0.58 * scale))], fill=GOLD_DARK + (140,))

    cx = CENTER * scale
    top, w, h = SHIELD_TOP * scale, SHIELD_W * scale, SHIELD_H * scale

    # Stars (small filled circles; at icon sizes they read as specks).
    for (sx, sy, sr) in (((20.0, 24.0, 1.6), (88.0, 30.0, 1.2), (30.0, 84.0, 1.1), (80.0, 86.0, 1.5))):
        d.ellipse([(sx - sr) * scale, (sy - sr) * scale, (sx + sr) * scale, (sy + sr) * scale],
                  fill=STEEL + (190,))

    # Shield with the V notch in its top edge.
    shield = [(cx - w, top), (cx - 7 * scale, top), (cx, top + NOTCH * scale),
              (cx + 7 * scale, top), (cx + w, top), (cx + w, top + h * 0.55)]
    shield += _quad((cx + w, top + h * 0.55), (cx + w, top + h * 0.94), (cx, top + h))
    shield += _quad((cx, top + h), (cx - w, top + h * 0.94), (cx - w, top + h * 0.55))
    d.polygon(shield, fill=STEEL + (255,))

    # The sun sits in the notch: cut the V out of the shield first.
    d.polygon([(cx - 9 * scale, top - 1), (cx + 9 * scale, top - 1), (cx, top + NOTCH * scale)],
              fill=tuple(int(BG_TOP[i] + (BG_BOTTOM[i] - BG_TOP[i]) * (top / size)) for i in range(3)) + (255,))
    sr = SUN_R * scale
    sy = SUN_CY * scale
    d.ellipse([cx - sr, sy - sr, cx + sr, sy + sr], fill=SUN + (255,))

    # Blade, guard, grip.
    tip, guard = (CENTER - 16.0) * scale, (CENTER + 14.0) * scale
    half = 4.8 * scale
    blade = [(cx, tip), (cx + half, tip + 11 * scale), (cx + half, guard),
             (cx + 13 * scale, guard), (cx + 13 * scale, guard + 4 * scale),
             (cx + 3.2 * scale, guard + 4 * scale), (cx + 3.2 * scale, guard + 13 * scale),
             (cx - 3.2 * scale, guard + 13 * scale), (cx - 3.2 * scale, guard + 4 * scale),
             (cx - 13 * scale, guard + 4 * scale), (cx - 13 * scale, guard),
             (cx - half, guard), (cx - half, tip + 11 * scale)]
    d.polygon(blade, fill=GOLD + (255,))
    d.line([(cx, (CENTER - 11) * scale), (cx, (CENTER + 10) * scale)], fill=GOLD_DARK + (220,),
           width=max(1, int(1.4 * scale)))

    if mask in ("circle", "round"):
        out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        m = Image.new("L", (size, size), 0)
        md = ImageDraw.Draw(m)
        if mask == "circle":
            md.ellipse([0, 0, size - 1, size - 1], fill=255)
        else:
            md.rounded_rectangle([0, 0, size - 1, size - 1], radius=int(size * 0.22), fill=255)
        out.paste(img, (0, 0), m)
        return out
    return img


def write_rasters():
    try:
        from PIL import Image  # noqa: F401
    except ImportError:
        print("Pillow is not installed: vector icons written, rasters skipped", file=sys.stderr)
        return
    densities = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for dpi, px in densities.items():
        folder = os.path.join(RES, "mipmap-" + dpi)
        os.makedirs(folder, exist_ok=True)
        draw_raster(px).save(os.path.join(folder, "ic_launcher.png"))
        draw_raster(px, mask="round").save(os.path.join(folder, "ic_launcher_round.png"))
    os.makedirs(DOCS_ASSETS, exist_ok=True)
    draw_raster(512).save(os.path.join(DOCS_ASSETS, "app_icon_preview.png"))
    print("wrote raster icons (48..192 px) and docs/assets/app_icon_preview.png")


def main():
    write_vectors()
    write_rasters()


if __name__ == "__main__":
    main()
