#!/usr/bin/env python3
"""make_placeholder_assets.py - generate tiny, self-made placeholder assets + manifest.

CLEAN-ROOM: every byte here is produced by this script from arithmetic (gradients, a checker
pattern, a few rectangles). Nothing is copied, unpacked, converted or resampled from the original
RAN EP7 release, from an APK, from a video, or from any third party. These files exist so the
asset pipeline (manifest parsing, missing-file handling, size and checksum verification) is fully
tested before real, properly licensed data exists. See docs/ASSETS.md.

Output (in mobile/android/app/src/main/assets/):
  assets_manifest.bin        ASCII manifest: "ran-assets 1" header + "name kind bytes checksum" rows
  ph_ground.bin              64x64 RGBA8 ground tile (checksum-verified, kind=texture)
  ph_block.bin               32x32 RGBA8 obstacle tile (kind=texture)
  ph_player.bin              16x16 RGBA8 sprite (kind=texture)
  ph_ui_frame.bin            48x24 RGBA8 panel (kind=raw; the HUD also draws it procedurally)

Usage:
  python3 mobile/assets/make_placeholder_assets.py           # writes the files
  python3 mobile/assets/make_placeholder_assets.py --check   # verifies them, writes nothing
Exit code 0 = ok, 1 = mismatch/missing (used by CI).
"""
import argparse
import hashlib
import struct
import sys
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parents[1] / "android" / "app" / "src" / "main" / "assets"
MANIFEST_NAME = "assets_manifest.bin"
MAGIC = b"PHP1"          # placeholder image: magic, then w, h (u16 LE), then w*h*4 bytes RGBA8


def _rgba(w, h, fn):
    """Builds a PHP1 file: a tiny PNG-like container of raw RGBA pixels."""
    body = bytearray()
    for y in range(h):
        for x in range(w):
            body.extend(fn(x, y))
    return MAGIC + struct.pack("<HH", w, h) + bytes(body)


def ground_tile():
    # Green-ish checker with a lighter border: unmistakably synthetic.
    return _rgba(64, 64, lambda x, y: (
        (28, 58, 30, 255) if (x // 8 + y // 8) % 2 == 0 else (36, 74, 38, 255)
    ) if not (x < 2 or y < 2 or x > 61 or y > 61) else (60, 110, 62, 255))


def block_tile():
    # Brown block with a darker edge.
    return _rgba(32, 32, lambda x, y: (
        (125, 96, 64, 255) if not (x < 3 or y < 3 or x > 28 or y > 28) else (78, 58, 38, 255)
    ))


def player_sprite():
    # A simple capsule: transparent outside a rounded body, bright core otherwise.
    def px(x, y):
        dx, dy = x - 7.5, y - 7.5
        if dx * dx + dy * dy > 56.0:
            return (0, 0, 0, 0)
        shade = 210 if abs(dx) < 2.5 else 150
        return (70, shade, 110, 255)
    return _rgba(16, 16, px)


def ui_frame():
    # Horizontal gradient bar with a 2 px highlight line (the HUD uses it as a fallback panel).
    return _rgba(48, 24, lambda x, y: (
        (18 + x, 22 + x // 2, 30 + x // 3, 235) if 1 < y < 22 else (200, 200, 220, 255)
    ))


# name -> (kind, builder). Order defines the manifest order (stable for diffing).
ASSETS = [
    ("ph_ground.bin", "texture", ground_tile),
    ("ph_block.bin", "texture", block_tile),
    ("ph_player.bin", "texture", player_sprite),
    ("ph_ui_frame.bin", "raw", ui_frame),
]


def fnv1a32(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def build():
    """Returns {name: bytes} and the manifest text."""
    files = {name: builder() for name, _kind, builder in ASSETS}
    lines = [
        "# Generated by mobile/assets/make_placeholder_assets.py - do not edit by hand.",
        "# CLEAN-ROOM: synthetic placeholders made by this script; no original game data.",
        "# name kind bytes checksum(fnv1a32, 8 lowercase hex)",
        "ran-assets 1",
    ]
    for name, kind, _builder in ASSETS:
        data = files[name]
        lines.append(f"{name} {kind} {len(data)} {fnv1a32(data):08x}")
    return files, "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate or verify the synthetic placeholder assets.")
    ap.add_argument("--check", action="store_true", help="verify existing files instead of writing")
    ap.add_argument("--out", default=str(OUT_DIR), help="asset directory (default: the APK's assets)")
    args = ap.parse_args(argv)

    out = Path(args.out)
    files, manifest = build()

    if args.check:
        problems = []
        mpath = out / MANIFEST_NAME
        if not mpath.is_file():
            problems.append(f"missing {MANIFEST_NAME}")
        elif mpath.read_text(encoding="ascii") != manifest:
            problems.append(f"{MANIFEST_NAME} differs from the generator (regenerate it)")
        for name, data in files.items():
            p = out / name
            if not p.is_file():
                problems.append(f"missing {name}")
            elif p.read_bytes() != data:
                problems.append(f"{name} differs ({p.stat().st_size} bytes on disk, "
                                f"{len(data)} expected, sha256 {hashlib.sha256(p.read_bytes()).hexdigest()[:12]})")
        if problems:
            for p in problems:
                print("FAIL", p)
            return 1
        print(f"assets ok: {len(files)} files + {MANIFEST_NAME} ({sum(len(d) for d in files.values())} bytes)")
        return 0

    out.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (out / name).write_bytes(data)
    (out / MANIFEST_NAME).write_text(manifest, encoding="ascii")
    print(f"wrote {len(files) + 1} files to {out}")
    for name, data in files.items():
        print(f"  {name:18s} {len(data):6d} B  fnv1a32={fnv1a32(data):08x}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
